/**
 * Generate adaptive drill dynamically targeting weak keys
 */
export function generateWeakKeyPassage(weakKeysMap = {}) {
  const sortedKeys = Object.entries(weakKeysMap)
    .filter(([k, stats]) => stats.errors > 0)
    .sort((a, b) => (b[1].rate || 0) - (a[1].rate || 0))
    .map(([k]) => k.toLowerCase())
    .slice(0, 5);

  if (sortedKeys.length === 0) {
    return {
      id: 'weak_dynamic_default',
      title: 'Adaptive Balance Drill',
      text: 'Perfect accuracy achieved! Keep your cadence steady across all keys: asdf jkl; qwer tyui op zxcv bnm with crisp and deliberate finger strikes.'
    };
  }

  // Word pool focused on specific tricky keys
  const keyWords = {
    'q': ['quick', 'quantum', 'equal', 'quote', 'query', 'equip', 'opaque', 'quiet'],
    'z': ['zero', 'zone', 'zigzag', 'freeze', 'quartz', 'blaze', 'bronze', 'maze'],
    'p': ['pipe', 'proper', 'pipette', 'prompt', 'purple', 'ripple', 'paper', 'apply'],
    'x': ['exact', 'complex', 'matrix', 'pixel', 'syntax', 'index', 'relax', 'oxygen'],
    'b': ['bubble', 'balance', 'vibrant', 'blanket', 'binary', 'beacon', 'robust'],
    'v': ['vivid', 'visual', 'velocity', 'canvas', 'valve', 'vortex', 'silver'],
    'w': ['wave', 'whisper', 'network', 'window', 'shadow', 'draw', 'flow'],
    'm': ['matrix', 'memory', 'moment', 'motion', 'mirror', 'minimal', 'prism'],
    'c': ['circle', 'circuit', 'crystal', 'cascade', 'dynamic', 'classic'],
    ';': ['item;', 'code;', 'data;', 'end;', 'call();', 'test;', 'return;'],
    ',': ['first,', 'second,', 'then,', 'however,', 'also,', 'truly,', 'smoothly,'],
    '.': ['done.', 'ready.', 'start.', 'stop.', 'next.', 'clear.', 'fluent.']
  };

  const pool = [];
  sortedKeys.forEach(k => {
    if (keyWords[k]) {
      pool.push(...keyWords[k]);
    } else {
      pool.push(k + 'a' + k, k + 'e' + k, 'in' + k, 'dis' + k);
    }
  });

  // Shuffle and assemble 35-45 words
  const generatedWords = [];
  for (let i = 0; i < 35; i++) {
    const word = pool[Math.floor(Math.random() * pool.length)];
    generatedWords.push(word);
  }

  return {
    id: 'weak_drill_' + Date.now(),
    title: `Targeted Drill: [ ${sortedKeys.join(', ').toUpperCase()} ]`,
    text: generatedWords.join(' ')
  };
}
